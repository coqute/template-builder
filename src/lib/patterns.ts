/**
 * 가릴 값의 모양 — AI로 보내기 전의 가림(src/ai/mask.ts)과, 문서를 밖으로 내보내기 전의 검사(게이트)가 함께 쓰는 부분.
 * 두 곳에 같은 식이 따로 있어 한쪽만 고쳐지는 일이 있었다(v0.25.0에서 가림의 IP만 문장 끝을 고쳤고 게이트는 v0.26.0에서야 고쳤다).
 *
 * 함께 쓰는 것: IPv4의 몸통과 앞뒤 조건, URL에 들지 않는 글자.
 * 일부러 따로 두는 것(합치면 동작이 달라진다):
 *  - 가림은 IP에 포트·CIDR을 붙여 통째로 가리고, 검사는 주소만 본다.
 *  - 검사에만 예외가 있다(0.0.0.0·루프백·네트워크 주소·버전 모양, 자리표시 URL, 예시 도메인) — 가림에 넣으면 그 값이 그대로 나간다.
 *  - 메일의 끝: 가림은 넓게(끝 조각이 숫자여도) 가리고, 검사는 오탐을 줄이려 글자 TLD만 본다.
 *  - 전화·키 문자열은 가림에만, 식별자(pid 등)·사전 실명은 검사에만 있다.
 */

/** IPv4 네 마디 (각 0~255) */
export const IPV4_BODY = String.raw`(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)`;
/** 앞이 숫자·점이면 IP가 아니다 (더 긴 숫자열의 일부) */
export const IPV4_BEFORE = String.raw`(?<![\d.])`;
/** 뒤가 숫자나 .숫자로 이어지면 IP가 아니다(1.2.3.4.5) — 문장 끝의 마침표("…는 192.0.2.40.")는 주소 뒤로 본다 */
export const IPV4_AFTER = String.raw`(?!\d|\.\d)`;
/** URL의 나머지 — 공백·괄호·따옴표·백틱에서 끝난다 */
export const URL_REST = '[^\\s<>"\'`)\\]]+';
